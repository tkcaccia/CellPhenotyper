#!/usr/bin/env python3
"""Add the bounded-disk HoVer-Net method to the current manuscript artifacts."""

from pathlib import Path
from shutil import copy2

from docx import Document


ROOT = Path(__file__).resolve().parents[1]
MANUSCRIPT_SOURCE = ROOT / "Manuscript" / "CellPhenotyper revised 170926 VSI RGB input formats.docx"
MANUSCRIPT_OUTPUT = ROOT / "Manuscript" / "CellPhenotyper revised 180926 HoVerNet bounded storage.docx"
SUPPLEMENT_SOURCE = ROOT / "deliverables" / "CellPhenotyper_Supplementary_Information_20260915.docx"
SUPPLEMENT_OUTPUT = ROOT / "deliverables" / "CellPhenotyper_Supplementary_Information_20260918.docx"


def find_prefix(document, prefix: str):
    matches = [paragraph for paragraph in document.paragraphs if paragraph.text.startswith(prefix)]
    if len(matches) != 1:
        raise RuntimeError(f"Expected one paragraph beginning {prefix!r}, found {len(matches)}")
    return matches[0]


def set_labeled_paragraph(paragraph, text: str) -> None:
    """Preserve the manuscript's bold inline method labels."""
    label, separator, body = text.partition(":")
    paragraph.clear()
    paragraph.add_run(label + separator).bold = True
    paragraph.add_run(body)


def update_manuscript() -> None:
    copy2(MANUSCRIPT_SOURCE, MANUSCRIPT_OUTPUT)
    document = Document(MANUSCRIPT_OUTPUT)
    method = find_prefix(document, "Multi-model cell segmentation:")
    set_labeled_paragraph(method, (
        "Multi-model cell segmentation: After StarDist, HoVer-Net with the fast MoNuSAC "
        "checkpoint and CellViT++ with a histopathology foundation-model encoder were applied "
        "to the same resolution-calibrated crop [26-28]. HoVer-Net used overlapping 4,096-pixel "
        "ownership cores at 0.25 micrometres per pixel with a 256-pixel context halo. Only cores "
        "intersecting the GrandQC clean-tissue mask were submitted, and half-open core ownership "
        "retained a detection when its centroid belonged to that core. At most 64 normalized JPEG "
        "tiles were materialized at once. The official model and tile post-processor were retained, "
        "whereas unused MAT files, RGB overlays and slide-wide prediction and instance maps were "
        "not written. Per-tile cell records were compressed immediately and merged into one "
        "gzip-compressed JSON file. Numeric upstream classes were retained with readable names. "
        "HoVer-Net contours were omitted by default because the role-aware consensus uses "
        "CellViT++ geometry; an explicit option retained them for sensitivity analyses. The "
        "original slide-wide implementation remained available as a compatibility mode. This "
        "bounded-storage implementation requires matched boundary-equivalence validation before "
        "release-quality biological claims."
    ))
    consensus = find_prefix(document, "Consensus cell identification:")
    set_labeled_paragraph(consensus, (
        "Consensus cell identification: Instances from StarDist, HoVer-Net and CellViT++ were "
        "linked by centroid distance after converting the default 4-micrometre matching radius "
        "to pixels from slide metadata. The default broad-pair policy required spatial agreement "
        "between StarDist and CellViT++, the two broad-scope detectors. HoVer-Net MoNuSAC was "
        "retained as class-specific supporting evidence and did not alter the canonical centroid "
        "or inflate broad-detector support. Canonical geometry followed the CellViT++ instance "
        "when available. The module emitted a consensus label image, object table, GeoJSON, "
        "model-to-consensus alignment table and support summary."
    ))
    document.save(MANUSCRIPT_OUTPUT)


def update_supplement() -> None:
    copy2(SUPPLEMENT_SOURCE, SUPPLEMENT_OUTPUT)
    document = Document(SUPPLEMENT_OUTPUT)
    consensus = find_prefix(document, "Consensus components are generated")
    consensus.text = (
        "Consensus components are generated by one-to-one physical-distance matching without "
        "permitting two detections from one source in the same component. The default broad-pair "
        "policy requires joint StarDist and CellViT++ support. HoVer-Net MoNuSAC contributes "
        "scoped class evidence but is not counted as a second broad detector. Pairwise benchmark "
        "files report detector counts, matched pairs, match fractions, median and 95th-percentile "
        "centroid distance, polygon IoU quartiles and Hausdorff distance. These outputs quantify "
        "agreement among algorithms and must not be described as expert-referenced accuracy."
    )
    anchor = find_prefix(document, "Supplementary Note 6 |")
    anchor.insert_paragraph_before(
        "Supplementary Note 6 | Bounded-disk HoVer-Net execution", style="Heading 1"
    )
    anchor.insert_paragraph_before(
        "Official HoVer-Net whole-slide inference allocates a four-channel float32 prediction "
        "map and an int32 instance map across the complete processed rectangle; these arrays can "
        "exceed 100 GB at 0.25 micrometres per pixel. The bounded default instead uses 4,096-pixel "
        "ownership cores with 256-pixel halos and skips cores without GrandQC clean-tissue support. "
        "Half-open centroid ownership retains each detection once. Batches are limited to 64 "
        "normalized tiles, bounding temporary image storage independently of slide area."
    )
    anchor.insert_paragraph_before(
        "The pinned upstream model and tile post-processing code are used. CellPhenotyper disables "
        "the upstream MAT, RGB overlay and raw-map writers, compresses tile JSON immediately, "
        "removes each input batch, and incrementally merges centroids, MoNuSAC classes and type "
        "probabilities. Contours are opt-in because broad-pair fusion uses CellViT++ geometry. The "
        "legacy whole-slide route remains available with Zarr or NumPy caches, and task exit removes "
        "all transient inputs, outputs and runtime copies. The prior Zarr-versus-NumPy equality test "
        "validates cache encoding only; the tiled route still requires a matched boundary audit."
    )
    # Renumber the former Note 6 and subsequent notes to keep the document sequence monotonic.
    for paragraph in document.paragraphs:
        if paragraph.style.name.startswith("Heading") and paragraph.text.startswith("Supplementary Note "):
            prefix, separator, title = paragraph.text.partition(" | ")
            try:
                number = int(prefix.removeprefix("Supplementary Note "))
            except ValueError:
                continue
            if number >= 6 and "Bounded-disk HoVer-Net" not in title:
                paragraph.text = f"Supplementary Note {number + 1}{separator}{title}"
    document.save(SUPPLEMENT_OUTPUT)


if __name__ == "__main__":
    update_manuscript()
    update_supplement()
    print(MANUSCRIPT_OUTPUT)
    print(SUPPLEMENT_OUTPUT)
